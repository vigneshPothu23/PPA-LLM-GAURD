"""Revision 2 of the InjecGuard training-candidate audit. Never trains, never edits inputs, never approves fine-tuning.

Reuses the validated v1 logic (experiments/scripts/audit_injecguard.py, imported unchanged) and changes the pipeline:

  1. load, schema, label-mapping evidence, record validation              (v1 logic)
  2. SOURCE-LEVEL exclusions first: policy exclusions (--exclude-source NAME=REASON) and any source that IS the dev set
  3. duplicates and conflicting labels, recomputed on what remains          (so a duplicate is never dropped in favour
                                                                             of a copy from an excluded source)
  4. leakage against dev, probe-dev, frozen test (read-only) and BIPIA test sources:
       exact normalised | loose normalised | word-3-gram Jaccard >= 0.80 | shingle containment >= 0.90 either way |
       reference verbatim inside candidate | candidate verbatim inside reference |
       shared sentence (normalised sentence of >= SENT_MIN_WORDS words occurring in both) |
       shared attack string (attack field of probe-dev rows)
  5. post-exclusion re-verification with every check above; any residual overlap -> FAIL
  6. reporting: label/metadata leakage scan, suspicious-label patterns, methodology-overlap sources,
     paired clean/poisoned variants inside the candidate, class balance, token lengths (only with a supplied tokenizer)

One primary exclusion reason per row (the first that applied, in pipeline order); every other reason that also
applied is recorded as a secondary flag. Kept rows get flags in kept_row_flags.jsonl (hashes only, no text).

Token lengths: computed only when --tokenizer points to a tokenizers JSON file. They are labelled VERIFIED only when
--expect-tokenizer-sha256 is given and matches; otherwise they are reported as unverified and the gate warns.
"""

from __future__ import annotations

import argparse
import bisect
import collections
import importlib.util
import json
import re
import statistics
import sys
from pathlib import Path

_V1 = Path(__file__).with_name("audit_injecguard.py")
_spec = importlib.util.spec_from_file_location("audit_injecguard_v1", _V1)
v1 = importlib.util.module_from_spec(_spec)
sys.modules["audit_injecguard_v1"] = v1
_spec.loader.exec_module(v1)

key, loose, shingles, sha, file_sha = v1.key, v1.loose, v1.shingles, v1.sha, v1.file_sha
Gate, CriticalError, RefIndex, Ref = v1.Gate, v1.CriticalError, v1.RefIndex, v1.Ref

SCRIPT_VERSION = "2.0.0"
OUTPUT_FILES = ("audit_report.json", "AUDIT_SUMMARY.md", "exclusion_manifest.jsonl", "dataset_manifest.json",
                "kept_row_flags.jsonl", "candidate_train.jsonl")
SENT_MIN_WORDS = 8          # sentences shorter than this are too generic to count as a shared sentence
LENGTH_BUCKETS = (128, 256, 512)
# Sources kept in the candidate whose construction resembles a frozen evaluation method (reported, not excluded)
METHOD_REVIEW = {
    "xtest-v2-copy": "XSTest-style benign prompts with unsafe-sounding trigger words (e.g. 'kill a process'); "
                     "the same over-defence idea as NotInject in the frozen validation/test sets",
    "TaskTracker": "indirect injections embedded in task data with paired clean/poisoned copies; same threat model as "
                   "the frozen BIPIA test (different generator and contexts)",
    "LLM Augmented set": "injections generated by the InjecGuard/NotInject authors; different label (injection) from "
                         "NotInject (benign) but the same research pipeline",
}
INJECTION_PHRASE = re.compile(
    r"\b(ignore|disregard|forget)\b[^.\n]{0,40}\b(previous|prior|above|earlier|all)\b[^.\n]{0,20}\b(instructions?|rules|prompts?|directions)\b",
    re.I)
SENT_SPLIT = re.compile(r"(?<=[.!?])\s+|\n+")


def sentences(text: str) -> set:
    out = set()
    for s in SENT_SPLIT.split(text):
        k = key(s)
        if len(re.findall(r"\w+", k)) >= SENT_MIN_WORDS:
            out.add(k)
    return out


def parse_exclusions(items) -> dict:
    out = {}
    for it in items or []:
        name, _, reason = it.partition("=")
        if not name or not reason:
            raise SystemExit(f"--exclude-source expects NAME=REASON, got {it!r}")
        out[name] = reason
    return out


def token_stats(texts_by_idx, labels_by_idx, sources_by_idx, tok_path: Path, max_tokens: int):
    from tokenizers import Tokenizer  # noqa: PLC0415  (only needed when a tokenizer is supplied)
    tok = Tokenizer.from_file(str(tok_path))
    tok.no_truncation()
    tok.no_padding()
    order = sorted(texts_by_idx)
    lens = {}
    for b in range(0, len(order), 2048):
        chunk = order[b:b + 2048]
        for i, enc in zip(chunk, tok.encode_batch([texts_by_idx[i] for i in chunk])):
            lens[i] = len(enc.ids)

    def summary(vals):
        if not vals:
            return None
        return {"n": len(vals), "min": min(vals), "median": statistics.median(vals), "mean": round(statistics.fmean(vals), 1),
                "max": max(vals), **{f"pct_over_{t}": round(100 * sum(v > t for v in vals) / len(vals), 2) for t in LENGTH_BUCKETS},
                f"truncated_at_{max_tokens}": sum(v > max_tokens for v in vals)}
    allv = list(lens.values())
    by_label = {str(l): summary([lens[i] for i in order if labels_by_idx[i] == l]) for l in sorted(set(labels_by_idx.values()))}
    by_source = {s: summary([lens[i] for i in order if sources_by_idx[i] == s]) for s in sorted(set(sources_by_idx.values()))}
    return lens, {"overall": summary(allv), "by_label": by_label, "by_source": by_source,
                  "tokenizer_vocab_size": tok.get_vocab_size(), "counted_with_special_tokens": True}


def audit(args) -> dict:
    gate = Gate()
    policy = parse_exclusions(args.exclude_source)
    report = {"script": "experiments/scripts/audit_injecguard_v2.py", "version": SCRIPT_VERSION,
              "reuses": {"experiments/scripts/audit_injecguard.py": file_sha(_V1)},
              "decision_note": "This audit does not approve fine-tuning. It reports whether a candidate could be prepared safely.",
              "parameters": {"near_jaccard": v1.NEAR_JACCARD, "containment": v1.CONTAIN, "min_shingles": v1.MIN_SHINGLES,
                             "posting_cap": v1.POSTING_CAP, "verbatim_min_chars": v1.VERBATIM_MIN,
                             "sentence_min_words": SENT_MIN_WORDS, "max_tokens": args.max_tokens,
                             "policy_source_exclusions": policy}}
    inputs = [p for p in [args.candidates, args.dev, args.frozen_test, *(args.extra_dev or []), args.eval_loader,
                          args.tokenizer] if p]
    before = {str(p): file_sha(p) for p in inputs if p.is_file()}
    report["label_mapping"] = {"mapping": {str(k): v for k, v in v1.LABEL_MAPPING.items()},
                               "evidence": v1.verify_label_evidence(args.label_evidence, gate)}

    # ---- 1. load + schema + record validation (v1 rules)
    try:
        cand = v1.load_records(args.candidates)
    except CriticalError as e:
        gate.fail("CANDIDATES_UNREADABLE", str(e))
        cand = []
    schema = v1.profile_schema(cand)
    it, il = v1.infer_fields(cand)
    schema.update({"declared_text_field": args.text_field, "declared_label_field": args.label_field,
                   "inferred_text_field": it, "inferred_label_field": il})
    report["candidate_schema"] = schema
    if not cand:
        gate.fail("EMPTY_DATASET", f"{args.candidates.name} has no records")
    elif (it, il) != (args.text_field, args.label_field):
        gate.fail("SCHEMA_MISMATCH", f"declared ({args.text_field}, {args.label_field}) vs inferred ({it}, {il})")

    stages = collections.OrderedDict(loaded=len(cand))
    reasons = collections.defaultdict(list)
    evid = collections.defaultdict(list)

    def flag(i, reason, **ev):
        if reason not in reasons[i]:
            reasons[i].append(reason)
        evid[i].append({"reason": reason, **ev})

    bad_label = []
    for i, r in enumerate(cand):
        if not isinstance(r, dict):
            flag(i, "NOT_AN_OBJECT")
            continue
        t, lab = r.get(args.text_field), r.get(args.label_field)
        if not isinstance(t, str):
            flag(i, "MISSING_TEXT")
        elif not t.strip():
            flag(i, "EMPTY_TEXT")
        if lab is None or isinstance(lab, bool) or not isinstance(lab, int):
            bad_label.append(i)
            flag(i, "INVALID_LABEL", value_type=type(lab).__name__)
        elif lab not in v1.LABEL_MAPPING:
            bad_label.append(i)
            flag(i, "UNEXPECTED_LABEL", value=lab)
    if bad_label:
        gate.fail("INVALID_OR_UNEXPECTED_LABELS", f"{len(bad_label)} records have a missing, non-integer or unmapped label")
    valid = [i for i in range(len(cand)) if not reasons.get(i)]
    n_blank = sum(1 for i, rs in reasons.items() if rs[0] in ("MISSING_TEXT", "EMPTY_TEXT"))
    if n_blank:
        gate.warn("EMPTY_OR_MISSING_TEXT", f"{n_blank} records excluded for missing or blank text")
    stages["after_record_validation"] = len(valid)

    T = lambda i: cand[i][args.text_field]  # noqa: E731
    L = lambda i: cand[i][args.label_field]  # noqa: E731
    S = lambda i: str(cand[i].get(args.source_field, ""))  # noqa: E731

    def label_counts(ids):
        c = collections.Counter(L(i) for i in ids)
        return {v1.LABEL_MAPPING[k]: c.get(k, 0) for k in sorted(v1.LABEL_MAPPING)}

    # ---- 2. source-level exclusions
    present = collections.Counter(S(i) for i in valid)
    for name in sorted(policy):
        if name not in present:
            gate.fail("POLICY_SOURCE_NOT_FOUND", f"--exclude-source {name!r} matches no source in the candidates")
    src_report = {}
    before_src = list(valid)
    for name, why in sorted(policy.items()):
        ids = [i for i in valid if S(i) == name]
        src_report[name] = {"rows_excluded": len(ids), "labels_excluded": label_counts(ids), "reason": why,
                            "kind": "policy", "status": "excluded from this candidate; retained in the source file for a separate experiment"}
        for i in ids:
            flag(i, "SOURCE_EXCLUDED_POLICY", source=name, policy_reason=why)
    dev_refs, dev_info = v1.load_eval_set(args.dev, "dev", args.dev_text_field, args.dev_label_field, gate, args.expect_dev_sha256)
    dev_keys = {key(r.text) for r in dev_refs}
    by_src = collections.defaultdict(lambda: [0, 0])
    for i in valid:
        by_src[S(i)][0] += 1
        by_src[S(i)][1] += key(T(i)) in dev_keys
    for s, (n, hit) in sorted(by_src.items()):
        if n >= args.dev_source_min_rows and hit / n >= args.dev_source_share:
            ids = [i for i in valid if S(i) == s]
            src_report[s] = {"rows_excluded": len(ids), "labels_excluded": label_counts(ids), "kind": "dev_set_source",
                             "reason": f"{hit} of {n} rows are dev-set texts (the frozen dev set was built from this source)"}
            for i in ids:
                flag(i, "SOURCE_IS_DEV_SET", source=s)
            gate.warn("DEV_SOURCE_EXCLUDED", f"{s}: {n} rows excluded (it is the dev set's source)")
    after_src = [i for i in valid if not reasons.get(i)]
    report["source_exclusions"] = {"by_source": src_report, "labels_before": label_counts(before_src),
                                   "labels_after": label_counts(after_src)}
    for name in policy:
        gate.warn("POLICY_SOURCE_EXCLUDED", f"{name}: {src_report.get(name, {}).get('rows_excluded', 0)} rows excluded ({policy[name]})")
    stages["after_source_exclusions"] = len(after_src)

    # ---- 3. duplicates and conflicts on what remains (and, for comparison, what v1 saw)
    pre_conf = collections.defaultdict(set)
    for i in valid:
        pre_conf[key(T(i))].add(L(i))
    groups = collections.defaultdict(list)
    for i in after_src:
        groups[key(T(i))].append(i)
    conflict = [g for g in groups.values() if len({L(i) for i in g}) > 1]
    for g in conflict:
        for i in g:
            flag(i, "CONFLICTING_LABELS", group_text_sha256=sha(key(T(i))), labels_in_group=sorted({L(j) for j in g}),
                 group_size=len(g), sources_in_group=sorted({S(j) for j in g}))
    removed = 0
    for g in groups.values():
        if len(g) > 1 and len({L(i) for i in g}) == 1:
            for i in g[1:]:
                removed += 1
                flag(i, "DUPLICATE_OF_KEPT_RECORD", kept_record=f"{args.candidates.name}#{g[0]}", exact_raw_match=T(i) == T(g[0]))
    raw = collections.Counter(T(i) for i in after_src)
    report["duplicates"] = {"scope": "after source exclusions",
                            "exact_raw_duplicate_groups": sum(c > 1 for c in raw.values()),
                            "exact_raw_extra_rows": sum(c - 1 for c in raw.values() if c > 1),
                            "normalized_extra_rows_removed": removed,
                            "conflicting_label_groups": len(conflict),
                            "conflicting_label_rows_excluded": sum(len(g) for g in conflict),
                            "conflicting_label_groups_before_source_exclusions": sum(len(v) > 1 for v in pre_conf.values())}
    if conflict:
        gate.warn("CONFLICTING_LABELS", f"{len(conflict)} texts carry both labels; all {sum(len(g) for g in conflict)} rows excluded")
    if removed:
        gate.warn("DUPLICATES_REMOVED", f"{removed} duplicate rows removed (first remaining occurrence kept)")
    after_dedup = [i for i in after_src if not reasons.get(i)]
    stages["after_dedup_and_conflicts"] = len(after_dedup)

    # ---- 4. leakage against reference sets
    test_refs, test_info = v1.load_eval_set(args.frozen_test, "test", args.dev_text_field, args.dev_label_field, gate,
                                            args.expect_test_sha256)
    refs = list(dev_refs) + list(test_refs)
    ref_info = {"dev": dev_info, "frozen_test": test_info, "extra_dev": []}
    for p in args.extra_dev or []:
        r2, info = v1.load_eval_set(p, "extra_dev", args.dev_text_field, args.dev_label_field, gate, None)
        refs += r2
        rows = v1.load_records(p) if p.is_file() else []
        atk = sorted({r[args.extra_dev_attack_field] for r in rows if isinstance(r, dict)
                      and isinstance(r.get(args.extra_dev_attack_field), str) and r[args.extra_dev_attack_field].strip()})
        refs += [Ref("extra_dev", f"{p.name}:attack#{j}", "probe_dev_attack", a) for j, a in enumerate(atk, 1)]
        info["attack_strings"] = len(atk)
        ref_info["extra_dev"].append(info)
    if args.bipia:
        r3, ref_info["bipia_test_sources"] = v1.load_bipia_test_sources(args.bipia, gate)
        refs += r3
    else:
        gate.warn("BIPIA_SOURCES_NOT_CHECKED", "no --bipia given")
    ref_info["eval_loader"] = v1.verify_eval_loader(args.eval_loader, args.dev_text_field, args.dev_label_field, gate)
    report["reference_sets"] = ref_info
    ROLE = {"dev": "OVERLAP_DEV", "extra_dev": "OVERLAP_PROBE_DEV", "test": "OVERLAP_FROZEN_TEST", "test_source": "OVERLAP_TEST_SOURCE"}

    idx = RefIndex(refs)
    ref_keys = [key(r.text) for r in refs]
    starts, pos = [], 0
    for k in ref_keys:
        starts.append(pos)
        pos += len(k) + 1
    big_ref = "\x00".join(ref_keys)
    indexed = set(idx.post) | set(idx.capped)
    sent_index = collections.defaultdict(set)
    for j, r in enumerate(refs):
        for s in sentences(r.text):
            sent_index[s].add(j)

    def overlaps(ids):
        verb = idx.verbatim({i: T(i) for i in ids})
        out = {}
        for i in ids:
            hits = list(idx.match(T(i)))
            seen = {j for _, j, _ in hits}
            hits += [h for h in verb.get(i, ()) if h[1] not in seen]
            seen |= {j for _, j, _ in hits}
            ck = key(T(i))
            sh = shingles(T(i))
            # a candidate can only sit verbatim inside a reference if every one of its shingles occurs in the references
            if len(ck) >= v1.VERBATIM_MIN and sh <= indexed:
                p = big_ref.find(ck)
                while p != -1:
                    j = bisect.bisect_right(starts, p) - 1
                    if j not in seen:
                        hits.append(("candidate_verbatim_in_reference", j, 1.0))
                        seen.add(j)
                    p = big_ref.find(ck, p + 1)
            for s in sentences(T(i)):
                for j in sorted(sent_index.get(s, ())):
                    if j not in seen:
                        hits.append(("shared_sentence", j, 1.0))
                        seen.add(j)
            if hits:
                out[i] = sorted(hits, key=lambda h: (h[1], h[0]))
        return out

    ov = overlaps(after_dedup)
    kinds = collections.Counter()
    by_src_reason = collections.defaultdict(collections.Counter)
    for i, hits in sorted(ov.items()):
        for kind, j, score in hits:
            r = refs[j]
            reason = ROLE[r.role]
            flag(i, reason, match=kind, score=score, reference=r.ref_id, reference_subset=r.subset, reference_text_sha256=sha(r.text))
            kinds[f"{reason}|{kind}"] += 1
        for reason in {ROLE[refs[j].role] for _, j, _ in hits}:
            by_src_reason[reason][S(i)] += 1
    report["overlap"] = {"matches_by_reason_and_kind": dict(sorted(kinds.items())),
                         "candidate_rows_by_reason_and_source": {k: dict(sorted(v.items())) for k, v in sorted(by_src_reason.items())}}
    for reason in sorted(by_src_reason):
        gate.warn(reason, f"{sum(by_src_reason[reason].values())} candidate rows overlap and were excluded")
    kept = [i for i in after_dedup if not reasons.get(i)]
    stages["after_leakage_exclusion"] = len(kept)

    # ---- 5. re-verification
    residual = overlaps(kept)
    report["post_exclusion_verification"] = {"remaining_overlaps": len(residual), "checks": [
        "exact normalised", "loose normalised", f"word-3-gram Jaccard >= {v1.NEAR_JACCARD}",
        f"shingle containment >= {v1.CONTAIN} either way", f"reference verbatim in candidate (>= {v1.VERBATIM_MIN} chars)",
        f"candidate verbatim in reference (>= {v1.VERBATIM_MIN} chars)", f"shared sentence (>= {SENT_MIN_WORDS} words)",
        "probe-dev attack strings"]}
    if residual:
        gate.fail("RESIDUAL_OVERLAP", f"{len(residual)} kept rows still overlap a reference set")
    if not kept:
        gate.fail("EMPTY_CANDIDATE", "no rows remain")

    # ---- 6. reporting on the kept rows
    kflags = collections.defaultdict(list)
    lab = collections.Counter(L(i) for i in kept)
    if kept and set(lab) != set(v1.LABEL_MAPPING):
        gate.fail("CLASS_MISSING", f"labels present: {dict(lab)}")
    n = len(kept)
    report["class_balance"] = {"rows": n, **{v1.LABEL_MAPPING[k]: lab.get(k, 0) for k in sorted(v1.LABEL_MAPPING)},
                               "pct": {v1.LABEL_MAPPING[k]: round(100 * lab.get(k, 0) / n, 2) for k in sorted(v1.LABEL_MAPPING)} if n else {},
                               "benign_per_injection": round(lab.get(0, 0) / lab[1], 3) if lab.get(1) else None}
    if n and min(lab.values()) / n < 0.25:
        gate.warn("CLASS_IMBALANCE", f"injection share {lab.get(1, 0) / n:.3f}; no resampling or relabelling was applied")
    src_counts = collections.defaultdict(collections.Counter)
    for i in kept:
        src_counts[S(i)][L(i)] += 1
    report["kept_by_source"] = {s: {v1.LABEL_MAPPING[k]: c.get(k, 0) for k in sorted(v1.LABEL_MAPPING)} for s, c in sorted(src_counts.items())}
    report["single_label_sources"] = sorted(s for s, c in src_counts.items() if len(c) == 1)

    # label / metadata leakage
    leak = {name: sum(1 for i in kept if re.search(p, T(i), re.I)) for name, p in v1.TARGET_LEAK_PATTERNS.items()}
    names = sorted({S(i) for i in kept if len(S(i)) >= 6})
    leak["source_name_in_text"] = dict(sorted(collections.Counter(s for i in kept for s in names if s.casefold() in T(i).casefold()).items()))
    leak["note"] = "candidate rows carry `source` and `id` as metadata; a training loader must feed only `text`"
    report["label_metadata_leakage_scan"] = leak
    if any(v for k, v in leak.items() if isinstance(v, int)) or leak["source_name_in_text"]:
        gate.warn("POSSIBLE_TARGET_LEAKAGE", "label-like patterns or source names occur in some texts")

    # suspicious-label pattern: benign rows containing a classic override phrase
    sus = collections.Counter()
    for i in kept:
        if L(i) == 0 and INJECTION_PHRASE.search(T(i)):
            sus[S(i)] += 1
            kflags[i].append("benign_with_override_phrase")
    report["suspicious_labels"] = {"pattern": INJECTION_PHRASE.pattern, "benign_rows_matching_by_source": dict(sorted(sus.items())),
                                   "note": "reported only; labels were not changed (quoted or discussed attacks can be benign)"}
    if sus:
        gate.warn("SUSPICIOUS_LABEL_PATTERN", f"{sum(sus.values())} benign rows contain an instruction-override phrase")

    # paired clean/poisoned variants inside the candidate (matters for any internal train/validation split)
    pairs = collections.Counter()
    for s in sorted(src_counts):
        if len(src_counts[s]) < 2:
            continue
        inj = [i for i in kept if S(i) == s and L(i) == 1]
        st, p0 = [], 0
        for i in inj:
            st.append(p0)
            p0 += len(key(T(i))) + 1
        big = "\x00".join(key(T(i)) for i in inj)
        for i in (i for i in kept if S(i) == s and L(i) == 0):
            k = key(T(i))
            if len(k) >= v1.VERBATIM_MIN:
                p = big.find(k)
                if p != -1:
                    j = inj[bisect.bisect_right(st, p) - 1]
                    group = f"pair:{sha(k)[:16]}"
                    kflags[i].append(group)
                    kflags[j].append(group)
                    pairs[s] += 1
    report["paired_variants"] = {"benign_rows_contained_in_an_injection_row_by_source": dict(sorted(pairs.items())),
                                 "note": "any validation split carved from this candidate must keep each pair group together"}
    if pairs:
        gate.warn("PAIRED_VARIANTS", f"{sum(pairs.values())} clean/poisoned pairs inside the candidate; split by group, not by row")

    for s in sorted(src_counts):
        if s in METHOD_REVIEW:
            gate.warn("METHODOLOGY_REVIEW", f"{s} ({sum(src_counts[s].values())} rows kept): {METHOD_REVIEW[s]}")
    report["methodology_review"] = {s: {"note": METHOD_REVIEW[s], "kept_rows": sum(src_counts[s].values())}
                                    for s in sorted(METHOD_REVIEW) if s in src_counts}

    # token lengths
    if args.tokenizer:
        lens, stats = token_stats({i: T(i) for i in kept}, {i: L(i) for i in kept}, {i: S(i) for i in kept},
                                  args.tokenizer, args.max_tokens)
        tsha = file_sha(args.tokenizer)
        verified = bool(args.expect_tokenizer_sha256) and tsha == args.expect_tokenizer_sha256
        report["token_lengths"] = {"status": "VERIFIED" if verified else "UNVERIFIED_TOKENIZER", "tokenizer": str(args.tokenizer),
                                   "tokenizer_sha256": tsha, "max_tokens": args.max_tokens, **stats}
        for i in kept:
            if lens[i] > args.max_tokens:
                kflags[i].append(f"over_{args.max_tokens}_tokens")
        if not verified:
            gate.warn("TOKEN_LENGTHS_UNVERIFIED", "tokenizer hash not confirmed against the intended model; statistics are indicative only")
        elif stats["overall"][f"truncated_at_{args.max_tokens}"]:
            gate.warn("TRUNCATION", f"{stats['overall'][f'truncated_at_{args.max_tokens}']} rows exceed {args.max_tokens} tokens; kept, not truncated here")
    else:
        chars = sorted(len(T(i)) for i in kept)
        report["token_lengths"] = {"status": "NOT_COMPUTED",
                                   "reason": "the intended tokenizer (protectai/deberta-v3-base-prompt-injection-v2, onnx/tokenizer.json) "
                                             "is not available locally; character counts below are NOT token counts",
                                   "max_tokens": args.max_tokens,
                                   "chars": {"min": chars[0], "median": statistics.median(chars), "max": chars[-1]} if chars else None}
        gate.warn("TOKEN_LENGTHS_NOT_COMPUTED", "intended tokenizer not available locally; token statistics were not produced")

    report["stages"] = dict(stages)
    report["exclusions_by_primary_reason"] = dict(sorted(collections.Counter(rs[0] for rs in reasons.values() if rs).items()))
    report["exclusions_any_reason"] = dict(sorted(collections.Counter(r for rs in reasons.values() for r in rs).items()))
    after = {p: file_sha(Path(p)) for p in before}
    if any(before[p] != after[p] for p in before):
        gate.fail("INPUT_CHANGED_DURING_RUN", str([p for p in before if before[p] != after[p]]))
    report["inputs_sha256"] = before
    report["status"], report["critical"], report["warnings"] = gate.status, gate.critical, gate.warnings
    return {"report": report, "cand": cand, "kept": kept, "reasons": reasons, "evid": evid, "kflags": kflags}


def write_outputs(args, res):
    out, rep, cand = args.out, res["report"], res["cand"]
    written = []

    def dump(name, text):
        (out / name).write_text(text, encoding="utf-8", newline="\n")
        written.append(name)

    lines = []
    for i in sorted(i for i, rs in res["reasons"].items() if rs):
        r = cand[i] if isinstance(cand[i], dict) else {}
        t = r.get(args.text_field)
        rs = res["reasons"][i]
        lines.append(json.dumps({"record_id": f"{args.candidates.name}#{i}", "source_index": i, "source": r.get(args.source_field),
                                 "label": r.get(args.label_field), "text_sha256": sha(t) if isinstance(t, str) else None,
                                 "primary_reason": rs[0], "secondary_flags": rs[1:], "evidence": res["evid"][i]},
                                sort_keys=True, ensure_ascii=False))
    dump("exclusion_manifest.jsonl", "\n".join(lines) + ("\n" if lines else ""))
    dump("kept_row_flags.jsonl", "".join(json.dumps({"id": f"{args.candidates.stem}:{i:06d}", "text_sha256": sha(cand[i][args.text_field]),
                                                     "flags": sorted(set(res["kflags"][i]))}, sort_keys=True) + "\n"
                                         for i in res["kept"] if res["kflags"].get(i)))
    cand_hash = None
    if rep["status"] != "FAIL":
        dump("candidate_train.jsonl", "".join(json.dumps({"id": f"{args.candidates.stem}:{i:06d}", "text": cand[i][args.text_field],
                                                          "label": cand[i][args.label_field],
                                                          "label_name": v1.LABEL_MAPPING[cand[i][args.label_field]],
                                                          "source": cand[i].get(args.source_field), "text_sha256": sha(cand[i][args.text_field])},
                                                         ensure_ascii=False, sort_keys=True) + "\n" for i in res["kept"]))
        cand_hash = file_sha(out / "candidate_train.jsonl")
    dump("audit_report.json", json.dumps(rep, indent=1, sort_keys=True, ensure_ascii=False) + "\n")
    manifest = {"script": rep["script"], "version": SCRIPT_VERSION, "status": rep["status"], "reuses": rep["reuses"],
                "sources": {"candidates": {"path": str(args.candidates), "sha256": rep["inputs_sha256"].get(str(args.candidates)),
                                           "records": rep["candidate_schema"]["records"]}, "reference_sets": rep["reference_sets"]},
                "schema": {"text_field": args.text_field, "label_field": args.label_field, "source_field": args.source_field},
                "label_mapping": rep["label_mapping"],
                "source_exclusions": rep["source_exclusions"],
                "preprocessing": [
                    "Output text and labels are the original values, unchanged; nothing is truncated, resampled or relabelled.",
                    "Order: record validation -> source exclusions (policy, dev-set source) -> duplicates/conflicts on the remainder -> leakage.",
                    "Duplicates on the normalised key keep the first remaining occurrence; texts carrying both labels are all excluded.",
                    "Each excluded row has one primary reason (first in pipeline order); all others are secondary_flags.",
                    "Leakage checks: " + "; ".join(rep.get("post_exclusion_verification", {}).get("checks", [])),
                ],
                "outputs": {"candidate_train.jsonl": cand_hash,
                            **{n: file_sha(out / n) for n in ("exclusion_manifest.jsonl", "kept_row_flags.jsonl", "audit_report.json")}},
                "nondeterministic_fields": [],
                "approval": "NOT APPROVED FOR FINE-TUNING. Candidate only; the training decision is separate."}
    dump("dataset_manifest.json", json.dumps(manifest, indent=1, sort_keys=True, ensure_ascii=False) + "\n")
    dump("AUDIT_SUMMARY.md", summary_md(rep, cand_hash))
    (out / v1.MARKER).write_text(json.dumps({"files": written}, indent=1) + "\n")


def summary_md(rep, cand_hash):
    L = [f"# InjecGuard candidate audit v2: **{rep['status']}**", "",
         "Not an approval to fine-tune. Candidate only.", "", "## Stages", "", "| Stage | Rows |", "| --- | --- |"]
    L += [f"| {k.replace('_', ' ')} | {v:,} |" for k, v in rep.get("stages", {}).items()]
    L += ["", "## Exclusions (primary reason)", "", "| Reason | Rows |", "| --- | --- |"]
    L += [f"| {k} | {v:,} |" for k, v in rep.get("exclusions_by_primary_reason", {}).items()]
    L += ["", "## Source exclusions", ""]
    for s, v in rep.get("source_exclusions", {}).get("by_source", {}).items():
        L.append(f"- **{s}** ({v['kind']}): {v['rows_excluded']:,} rows {v['labels_excluded']} — {v['reason']}")
    cb = rep.get("class_balance", {})
    L += ["", "## Class balance", "", f"- {cb}"]
    tl = rep.get("token_lengths", {})
    L += ["", "## Token lengths", "", f"- Status: **{tl.get('status')}**" + (f" — {tl['reason']}" if tl.get("reason") else "")]
    if tl.get("overall"):
        L.append(f"- Overall: {tl['overall']}")
    L += ["", "## Leakage re-verification", "", f"- Remaining overlaps: {rep.get('post_exclusion_verification', {}).get('remaining_overlaps')}"]
    L += [f"- {c}" for c in rep.get("post_exclusion_verification", {}).get("checks", [])]
    if cand_hash:
        L += ["", f"candidate_train.jsonl sha256 `{cand_hash}`"]
    L += ["", "## Critical", ""] + ([f"- **{c['code']}**: {c['detail']}" for c in rep["critical"]] or ["- none"])
    L += ["", "## Warnings", ""] + ([f"- **{w['code']}**: {w['detail']}" for w in rep["warnings"]] or ["- none"])
    return "\n".join(L) + "\n"


def parse(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    for a in ("--candidates", "--dev", "--frozen-test", "--out"):
        ap.add_argument(a, type=Path, required=True)
    for a in ("--label-evidence", "--bipia", "--eval-loader", "--tokenizer"):
        ap.add_argument(a, type=Path)
    ap.add_argument("--extra-dev", type=Path, action="append")
    ap.add_argument("--extra-dev-attack-field", default="attack")
    ap.add_argument("--exclude-source", action="append", metavar="NAME=REASON")
    ap.add_argument("--overwrite", action="store_true")
    ap.add_argument("--text-field", default="prompt")
    ap.add_argument("--label-field", default="label")
    ap.add_argument("--source-field", default="source")
    ap.add_argument("--dev-text-field", default="text")
    ap.add_argument("--dev-label-field", default="label")
    ap.add_argument("--dev-source-share", type=float, default=0.95)
    ap.add_argument("--dev-source-min-rows", type=int, default=20)
    ap.add_argument("--max-tokens", type=int, default=512)
    ap.add_argument("--expect-dev-sha256")
    ap.add_argument("--expect-test-sha256")
    ap.add_argument("--expect-tokenizer-sha256")
    return ap.parse_args(argv)


def main(argv=None) -> int:
    args = parse(argv)
    try:
        protected = [args.candidates, args.dev, args.frozen_test, *(args.extra_dev or [])]
        protected += [x for x in (args.bipia, args.label_evidence) if x]
        v1.prepare_out(args.out, args.overwrite, protected)
    except CriticalError as e:
        print(f"OUTPUT REFUSED: {e}", file=sys.stderr)
        return 3
    res = audit(args)
    write_outputs(args, res)
    rep = res["report"]
    print(f"status: {rep['status']}")
    print(json.dumps({"stages": rep.get("stages"), "exclusions": rep.get("exclusions_by_primary_reason"),
                      "critical": [c["code"] for c in rep["critical"]], "warnings": [w["code"] for w in rep["warnings"]]}, indent=1))
    return 2 if rep["status"] == "FAIL" else 0


if __name__ == "__main__":
    sys.exit(main())
