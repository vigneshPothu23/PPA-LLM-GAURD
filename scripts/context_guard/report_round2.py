"""Render comparison_round2.json into comparison_round2.md and the ROUND2 block of CONTEXT_GUARD.md."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
J = ROOT / "docs/v5/evidence/context_guard/comparison_round2.json"
MD = ROOT / "docs/v5/evidence/context_guard/comparison_round2.md"
DOC = ROOT / "docs/v5/CONTEXT_GUARD.md"
MODELS = ["two_stage", "protectai", "protectai_card", "guard_full", "roberta6l", "scratch", "deepset", "fmops"]
NAME = {"two_stage": "Two-stage (round 2)", "protectai": "ProtectAI (default), dev thresholds",
        "protectai_card": "ProtectAI, app card thresholds 0.01/0.99", "guard_full": "Context guard (round 1)",
        "roberta6l": "roberta6l", "scratch": "scratch", "deepset": "deepset", "fmops": "fmops"}
TITLE = {"unseen_email_3": "Round-2 test: attacker-written e-mails vs real Enron mail (clean, scored once)",
         "unseen_embed_3": "Round-2 test: injections embedded in real Enron e-mails (clean, scored once)",
         "frozen_test": "Frozen test (development-influenced for round 2)",
         "unseen_synth": "Unseen synthetic documents (development-influenced)",
         "unseen_email": "Unseen e-mail, round 1 (development-influenced)",
         "unseen_email_2": "Confirmatory e-mail, round 1 (development-influenced)",
         "frozen_dev": "Frozen dev, direct prompts (development-influenced; out of scope)"}


def f(v, d=3):
    return "–" if v is None else f"{v:.{d}f}"


def ci(c):
    return "" if not c else f" [{f(c[0], 2)}–{f(c[1], 2)}]"


def tables(d, sets, with_subsets=True) -> list[str]:
    o = []
    for s in sets:
        res = d["sets"][s]
        o += [f"### {TITLE[s]}", "", "| Model | ROC-AUC | WARN P | R | F1 | FPR | BLOCK P | R | FPR |",
              "|---|---|---|---|---|---|---|---|---|"]
        for m in MODELS:
            r = res[m]
            w, b, c = r["at"]["WARN"], r["at"]["BLOCK"], r["ci95"]
            o.append(f"| {NAME[m]} | {f(r['roc_auc'])}{ci(c['roc_auc'])} | {f(w['precision'])} | {f(w['recall'])}"
                     f"{ci(c['warn_recall'])} | {f(w['f1'])} | {f(w['fpr'])}{ci(c['warn_fpr'])} | {f(b['precision'])} | "
                     f"{f(b['recall'])} | {f(b['fpr'])} |")
        o.append("")
        if with_subsets:
            subs = list(res["two_stage"]["subsets"])
            o += ["| Subset (WARN) | n | " + " | ".join(NAME[m].split(",")[0] for m in MODELS) + " |",
                  "|---|---|" + "---|" * len(MODELS)]
            for sub in subs:
                a0 = res["two_stage"]["subsets"][sub]
                key = "recall" if a0["pos"] else "fpr"
                vals = [f(res[m]["subsets"][sub]["at"]["WARN"][key], 2) for m in MODELS]
                o.append(f"| {sub} ({'recall' if a0['pos'] else 'FPR'}) | {a0['n']} | " + " | ".join(vals) + " |")
            o.append("")
    return o


def main():
    d = json.loads(J.read_text())
    h = d["hypotheses"]
    verdict = ["| Pre-registered hypothesis | Two-stage | ProtectAI | Holds? |", "|---|---|---|---|",
               f"| H4: e-mail ROC-AUC non-inferior (≥ ProtectAI − 0.02) | {f(h['H4_email_auc_noninferior']['two_stage'])} | "
               f"{f(h['H4_email_auc_noninferior']['protectai'])} | {'yes' if h['H4_email_auc_noninferior']['holds'] else '**no**'} |",
               f"| H5: embedded ROC-AUC superior | {f(h['H5_embedded_auc_superior']['two_stage'])} | "
               f"{f(h['H5_embedded_auc_superior']['protectai'])} | {'yes' if h['H5_embedded_auc_superior']['holds'] else '**no**'} |",
               f"| H6: pooled WARN: FPR ≤ and recall ≥ −0.05 | R {f(h['H6_pooled_warn']['two_stage']['recall'])}, "
               f"FPR {f(h['H6_pooled_warn']['two_stage']['fpr'])} | R {f(h['H6_pooled_warn']['protectai']['recall'])}, "
               f"FPR {f(h['H6_pooled_warn']['protectai']['fpr'])} | {'yes' if h['H6_pooled_warn']['holds'] else '**no**'} |",
               "", f"**Improvement validated (all three hold): {'YES' if h['improvement_validated'] else 'NO'}.**", ""]
    th = d["thresholds"]
    thr = ["| Model | WARN | BLOCK |", "|---|---|---|"] + [f"| {NAME[m]} | {th[m]['WARN']:.2f} | {th[m]['BLOCK']:.2f} |" for m in MODELS]
    clean = [s for s in d["sets"] if d["sets"][s].get("_clean_test")]
    earlier = [s for s in d["sets"] if not d["sets"][s].get("_clean_test")]
    full = ["# Round 2 — document-aware second stage vs existing detectors", "",
            f"Generated by `scripts/context_guard/report_round2.py` from `comparison_round2.json`. Artifact SHA-256 "
            f"`{d['artifact_sha256']}` (pre-registered). All thresholds were chosen on the same development data "
            "(ctx_dev + dev2_email).", "", "## Verdict", ""] + verdict + ["## Thresholds", ""] + thr + [""] + \
        ["## Clean round-2 test sets", ""] + tables(d, clean) + ["## Earlier sets (development-influenced for round 2)", ""] + \
        tables(d, earlier, with_subsets=False)
    MD.write_text("\n".join(full) + "\n")
    block = ["The tables below are generated from `evidence/context_guard/comparison_round2.json`. Full detail, including "
             "earlier sets: [comparison_round2.md](evidence/context_guard/comparison_round2.md).", ""] + verdict + \
        tables(d, clean)
    t = DOC.read_text()
    a, b = "<!-- ROUND2:BEGIN (generated by scripts/context_guard/report_round2.py) -->", "<!-- ROUND2:END -->"
    if a in t:
        pre, rest = t.split(a, 1)
        _, post = rest.split(b, 1)
        DOC.write_text(pre + a + "\n" + "\n".join(block) + "\n" + b + post)
        print("updated ROUND2 block")
    print("wrote", MD)


if __name__ == "__main__":
    main()
