"""Render docs/v5/evidence/context_guard/comparison.json into comparison.md (no hand-typed numbers)."""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
J = ROOT / "docs/v5/evidence/context_guard/comparison.json"
MD = ROOT / "docs/v5/evidence/context_guard/comparison.md"

LABEL = {
    "guard_full": "Context guard (full)",
    "guard_no_offtopic": "  ablation: no off-topic",
    "guard_no_detector": "  ablation: no localised detector",
    "guard_cues_only": "  ablation: cues only",
    "protectai_wholedoc": "ProtectAI v2, whole document (current default)",
    "roberta6l": "roberta6l int8 (ours), whole document",
    "scratch": "scratch (ours), whole document",
    "deepset": "deepset DeBERTa, whole document (frozen-dev-contaminated)",
    "fmops": "fmops DistilBERT, whole document (frozen-dev-contaminated)",
    "hybrid_max": "hybrid_max = max(guard, ProtectAI) — POST HOC",
}
SET_TITLE = {
    "frozen_dev": "Frozen dev (deepset direct prompts + NotInject) — direct injection is out of the guard's scope",
    "frozen_test": "Frozen test (BIPIA hidden e-mail/table/code injections + NotInject trigger-word prompts)",
    "unseen_synth": "Unseen synthetic documents (pool B carriers + held-out TaskTracker injections) — "
                    "the injected strings are in the Engine 2 training candidate, so roberta6l and scratch were "
                    "trained on them (their numbers here are not a generalisation measure)",
    "unseen_email": "Unseen real e-mails (LLMail-Inject phase-1 attacks + LLMail FP set + Enron)",
    "unseen_email_2": "CONFIRMATORY e-mails (LLMail-Inject phase-2 attacks + fresh Enron), pre-registered, scored once",
}


def f(v, d=3):
    return "–" if v is None else f"{v:.{d}f}"


def ci(c):
    return "" if not c else f" [{f(c[0], 2)}–{f(c[1], 2)}]"


def main():
    d = json.loads(J.read_text())
    models = list(d["thresholds"])
    o = ["# Context guard vs existing detectors — measured comparison", "",
         "Generated by `scripts/context_guard/report_context.py` from `comparison.json`; no number is typed by hand.",
         "", f"Protocol: {d['protocol']}. ctx_dev: {d['ctx_dev_n']} documents ({d['ctx_dev_pos']} injected).",
         "Post-hoc models (defined after seeing an unseen-set result): " + ", ".join(d["post_hoc_models"]) + ".",
         "Brackets are 95% bootstrap intervals (1000 resamples).", ""]

    o += ["## Component justification on development data (5-fold CV on ctx_dev)", "",
          "| Variant | out-of-fold ROC-AUC | out-of-fold AP |", "|---|---|---|"]
    for k, v in d["cross_validation_ctx_dev"].items():
        o.append(f"| {LABEL.get(k, k).strip()} | {f(v['oof_roc_auc'])} | {f(v['oof_average_precision'])} |")
    o.append("")

    o += ["## Thresholds (selected on ctx_dev, FPR-bounded rule, then frozen)", "",
          "| Model | WARN | BLOCK | Selection notes |", "|---|---|---|---|"]
    for m in models:
        t = d["thresholds"][m]
        notes = re.sub(r"(\d+\.\d{3})\d+", r"\1", "; ".join(d["threshold_notes"][m] or [])) or "targets met"
        o.append(f"| {LABEL.get(m, m).strip()} | {t['WARN']:.2f} | {t['BLOCK']:.2f} | {notes} |")
    o.append("")

    for s, res in d["sets"].items():
        o += [f"## {SET_TITLE.get(s, s)}", "",
              "| Model | ROC-AUC | WARN: P | R | F1 | FPR | BLOCK: P | R | FPR |",
              "|---|---|---|---|---|---|---|---|---|"]
        for m in models:
            r = res[m]
            w, b, c = r["at"]["WARN"], r["at"]["BLOCK"], r["ci95"]
            o.append(f"| {LABEL.get(m, m).strip()} | {f(r['roc_auc'])}{ci(c['roc_auc'])} | {f(w['precision'])} | "
                     f"{f(w['recall'])}{ci(c['warn_recall'])} | {f(w['f1'])} | {f(w['fpr'])}{ci(c['warn_fpr'])} | "
                     f"{f(b['precision'])} | {f(b['recall'])} | {f(b['fpr'])} |")
        o.append("")
        subs = list(next(iter(res.values()))["subsets"])
        o += [f"Per carrier at WARN (recall on injected rows / FPR on benign rows):", "",
              "| Carrier | n (inj) | " + " | ".join(LABEL.get(m, m).strip().split(",")[0].replace("  ablation: ", "−")
                                                  for m in models) + " |",
              "|---|---|" + "---|" * len(models)]
        for sub in subs:
            s0 = res[models[0]]["subsets"][sub]
            cells = []
            for m in models:
                a = res[m]["subsets"][sub]["at"]["WARN"]
                parts = []
                if a["pos"]:
                    parts.append(f"R {f(a['recall'], 2)}")
                if a["n"] - a["pos"]:
                    parts.append(f"FPR {f(a['fpr'], 2)}")
                cells.append(" / ".join(parts))
            o.append(f"| {sub} | {s0['n']} ({s0['pos']}) | " + " | ".join(cells) + " |")
        o.append("")

    o += ["## Fusion weights fitted on ctx_dev (standardised features)", ""]
    for name, w in d["guard_weights"].items():
        o.append(f"- **{LABEL.get(name, name).strip()}**: " +
                 ", ".join(f"{k} {v:+.2f}" for k, v in sorted(w.items(), key=lambda x: -abs(x[1])) if v))
    MD.write_text("\n".join(o) + "\n")
    print(f"wrote {MD} ({len(o)} lines)")
    inject_headline(d)


SHORT = {"guard_full": "Context guard", "protectai_wholedoc": "ProtectAI (default)", "hybrid_max": "hybrid_max (post hoc)",
         "roberta6l": "roberta6l", "scratch": "scratch", "deepset": "deepset", "fmops": "fmops"}
HEAD_MODELS = ["guard_full", "protectai_wholedoc", "hybrid_max", "roberta6l", "scratch", "deepset", "fmops"]
HEAD_SETS = ["frozen_test", "unseen_email", "unseen_email_2", "unseen_synth", "frozen_dev"]
SET_SHORT = {"frozen_test": "Frozen test", "unseen_email": "Unseen e-mail", "unseen_email_2": "Confirmatory e-mail",
             "unseen_synth": "Unseen synthetic docs", "frozen_dev": "Frozen dev (direct; out of scope)"}
INJ = [("frozen_test", "bipia_email", "BIPIA hidden in e-mail"), ("frozen_test", "bipia_table", "BIPIA hidden in table"),
       ("frozen_test", "bipia_code", "BIPIA hidden in code"), ("unseen_synth", "email", "synthetic e-mail"),
       ("unseen_synth", "document", "synthetic document"), ("unseen_synth", "table", "synthetic table"),
       ("unseen_synth", "code", "synthetic code"), ("unseen_email", "llmail", "LLMail phase-1 attack e-mail"),
       ("unseen_email_2", "llmail_phase2", "LLMail phase-2 attack e-mail (confirmatory)")]
BEN = [("frozen_test", "notinject_two", "NotInject trigger-word prompts (2)"),
       ("frozen_test", "notinject_three", "NotInject trigger-word prompts (3)"),
       ("frozen_dev", "notinject_one", "NotInject trigger-word prompts (1, dev)"),
       ("unseen_synth", "trigger", "synthetic docs with trigger words"), ("frozen_test", "bipia_email", "clean BIPIA e-mails"),
       ("frozen_test", "bipia_table", "clean BIPIA tables"), ("frozen_test", "bipia_code", "clean BIPIA code"),
       ("unseen_email", "llmail_fp", "LLMail benign FP-test e-mails"), ("unseen_email", "enron_ham", "real Enron e-mails"),
       ("unseen_email_2", "enron_ham_2", "real Enron e-mails (confirmatory)")]


def headline(d) -> str:
    present = [m for m in HEAD_MODELS if m in d["thresholds"]]
    o = ["Every value below is generated from `docs/v5/evidence/context_guard/comparison.json` at the WARN threshold "
         "each model was given on ctx_dev. Full tables, BLOCK-band results, ablations and confidence intervals: "
         "[evidence/context_guard/comparison.md](evidence/context_guard/comparison.md).", "",
         "**Overall** (ROC-AUC is threshold-free; P / R / F1 / FPR at WARN)", "",
         "| Set | n (inj) | " + " | ".join(SHORT[m] for m in present) + " |", "|---|---|" + "---|" * len(present)]
    for s in HEAD_SETS:
        if s not in d["sets"]:
            continue
        r0 = d["sets"][s][present[0]]
        cells = []
        for m in present:
            r = d["sets"][s][m]
            w = r["at"]["WARN"]
            cells.append(f"AUC {f(r['roc_auc'], 2)}<br>P {f(w['precision'], 2)} R {f(w['recall'], 2)}<br>"
                         f"F1 {f(w['f1'], 2)} FPR {f(w['fpr'], 2)}")
        o.append(f"| {SET_SHORT[s]} | {r0['n']} ({r0['pos']}) | " + " | ".join(cells) + " |")
    for title, rows, key in (("**Hidden-injection recall** (share of injected documents flagged, WARN)", INJ, "recall"),
                             ("**False-positive rate on benign content** (share flagged, WARN)", BEN, "fpr")):
        o += ["", title, "", "| Subset | n | " + " | ".join(SHORT[m] for m in present) + " |",
              "|---|---|" + "---|" * len(present)]
        for s, sub, lab in rows:
            if s not in d["sets"] or sub not in d["sets"][s][present[0]]["subsets"]:
                continue
            cnt = d["sets"][s][present[0]]["subsets"][sub]
            n = cnt["pos"] if key == "recall" else cnt["n"] - cnt["pos"]
            vals = [f(d["sets"][s][m]["subsets"][sub]["at"]["WARN"][key], 2) for m in present]
            o.append(f"| {lab} | {n} | " + " | ".join(vals) + " |")
    return "\n".join(o)


def inject_headline(d) -> None:
    doc = ROOT / "docs/v5/CONTEXT_GUARD.md"
    if not doc.exists():
        return
    text = doc.read_text()
    a, b = "<!-- HEADLINE:BEGIN (generated by scripts/context_guard/report_context.py) -->", "<!-- HEADLINE:END -->"
    if a in text and b in text:
        pre, rest = text.split(a, 1)
        _, post = rest.split(b, 1)
        doc.write_text(pre + a + "\n" + headline(d) + "\n" + b + post)
        print(f"updated headline tables in {doc}")


if __name__ == "__main__":
    main()
